"""报价质量标记 —— 把「价格不能代表这个型号行情」的条目挑出来。

为什么需要它（2026-10-03，由用户的一个提问引出）
-------------------------------------------------
用户问「RTX 4060 8G 历史最低 899 对吗？跌了 43%？现在 1299？」——三个数全不对：

  · **899 是假的**：来自闲鱼一条**多商品捆绑列表**，标题是
      「全新未拆封梅捷5070 12GD7 焱龙双扇白色6449元，全新三年保梅捷RTX4060 8G白色
        2579元，…全新三年保梅捷1650 4GD6 899元，…」
    899 是**「梅捷1650 4GD6」的价格**，却因为标题里出现了「RTX4060 8G」，
    这条被归到了 4060 型号名下 —— 直接造出一个虚假的「历史最低」。
  · **1299 是坏卡**：标题明写「图四图五有瑕疵 **无法点亮**。看好再买 售出不退」。
  · **43%** 就是拿这两个假数据算出来的。

根因：**型号归属只看标题关键词，没有校验「这条价格是否属于这个型号」**。
一条挂 5 个型号的批发列表，会被归到它提到的**每一个**型号名下，
而它的 price 是卖家填的**起价**（往往是最便宜那款）。

判据是**用真实库逐词核对出来的**（不是拍脑袋）
-------------------------------------------------
标 `bundle`：标题含 **≥3 处「N元」**。
  · 为什么是 3 而不是 2：实测 2 处的 71 条里有大量误杀 —— 卖家常写
    「1999元买的，现在1950元」「已经有多人出到3100元」这类**议价叙述**。
  · ≥3 处的 14 条（去重后 3 种）**全部**是多商品列表（"型号1/型号2/型号3"、
    整机拆卖、以及那条 899 的来源）—— **零误杀**。

标 `industrial`：工业 / 非零售渠道卡（涡轮、工包、算力卡）。
  见下方 `_INDUSTRIAL_WORDS` 的逐词核对记录。**这是 2026-10-03「4080 Super
  一天涨 44%」的直接成因**：京东 10-02 那轮采到的 3 条全是涡轮/工包卡
  （¥9800 / ¥11515 / ¥15000），而 09-30 那条是零售卡（影驰金属大师 ¥7039）——
  最低价"换人"了，就被读成 +39%（d7 用 09-25 的技嘉 ¥6799 做基准 = +44%）。

标 `defective`：只收**逐词全量核对过**的词。
  · `无法点亮`(4) `坏卡`(13) `坏显卡`(4) `当坏件`(3) `坏的坏的`(15) `故障配件`(1)
    → 全部是真坏卡，**零误杀**。
  · `点不亮`(41)：核对到约 3% 误杀（例：某卡「普通台式机 pci-e 点不亮，
    必须服务器 pci-e」——卡是好的）。**仍然收录**，因为漏标的代价更大：
    这 41 条里坏卡的报价普遍是正常价的 1/5，漏标会显著拉低「历史最低」
    （正是用户被误导的根源）。已知误差写在这里，便于日后复查。

  ⚠️ **反面教材（试过、误杀严重、已剔除）** —— 记下来免得以后有人再加：
    · `无核心` → 命中的是「无暗病无维修**无核心重植**」（正常卡的**正面**描述）
    · `无卡`   → 命中的是「打**无卡**顿」
    · `修不了` → 命中的是「4060**修不了**换的这张5050」（卖家在讲来源，卡是全新的）
    · `坏的`   → 命中的是「风扇**坏的**！！！！其他功能正常」（是配件坏，不是卡坏）
    · `不亮机` / `开不了机` → 命中的是「**开不了机**箱」「**不亮机**箱风扇」这类无关短语
    · `维修` / `配件` / `散热器` / `支架` / `包装盒` → 「箱说齐全，自带原装显卡支架」
      「配件齐全」都是**正常商品**的常见描述（一版收进来过，3627 条里绝大多数是正常卡）
  ⇒ 共同教训：**同一词在不同上下文里意思可能相反，纯子串匹配必须逐词核对误杀率。**

用法
----
用法
----
标记进 `listings.quality_flags`（逗号分隔），随明细落盘 → **可追溯**（不静默丢弃）。
统计侧**一律排除** `SUSPECT_FLAGS` 全集：
  · `aggregate.refresh_daily` —— 聚合入口（行情底座，必须在这里挡住）
  · `services.report` —— 日报/比价表
三者共用 `SUSPECT_FLAGS` 定义，避免口径漂移。
"""
from __future__ import annotations

import re

# 「N元」—— 支持千分位与全角逗号
_PRICE_CNY_RE = re.compile(r"\d[\d,，]*\s*元")

# 标题里出现 ≥3 个价格 → 多商品列表（价格与型号的对应关系不可靠）
_BUNDLE_PRICE_MIN = 3

# 坏卡 / 非完整卡。每个词都经过真实库全量核对（零误杀，例外只有「点不亮」见模块说明）。
_DEFECTIVE_WORDS: tuple[str, ...] = (
    "无法点亮",      # 4/4 真坏卡
    "坏卡",          # 13/13 真坏卡
    "坏显卡",        # 4/4 真坏卡
    "当坏件",        # 3/3 真坏卡
    "坏的坏的",      # 15/15 真坏卡（卖家重复强调，强信号）
    "故障配件",      # 1/1 真坏卡
    "点不亮",        # 41 条，约 3% 误杀（已知，见模块说明）
    # 残次 CPU：内存控制器只有一半能用（"内存单通道（只可以一根内存使用）"）。
    # 漏标的代价实测过：Ryzen 9 9950X3D 有一条 ¥2400 的"只能单通道使用"，
    # 被当成该型号最低价，次日样本回复正常后算出 **+45.83% 的假暴涨**。
    "单通道",        # 53/53 全是残次 CPU → 零误杀
)

# 逐词核对过、但**否定式占比过高不能收**的词（2026-10-03 统计，记下来别再试）：
#   · `蓝屏`   57 条里 52 条是「不蓝屏」   · `花屏`   32 条里 20 条是「不花屏」
#   · `掉驱动` 30 条里 21 条是「不掉驱动」 · `有维修` 27 条里 21 条是「无维修」
#   · `修过`   851 条里绝大多数是「没修过」 · `暗病` 1915 条多为「无暗病」
#   · `无核显` 782 条是 F 系列 CPU 的**事实描述**，不是缺陷
#   ⇒ 这些只能靠"否定式检测"（前后缀）才能用，纯子串一定会大面积误杀。

# 工业 / 非零售渠道卡。价格体系与零售消费卡完全不同（普遍高 30~100%），
# 混进「全新」口径会直接顶掉最低价、造出假涨跌 —— 必须单独成类。
#
# 逐词核对记录（2026-10-03，真实库 25530 条真实明细上抽样）：
#   · `涡轮`      180 条，抽样 30 条**全部**是涡轮散热卡 / 服务器卡 / 工包卡 → 零误杀
#   · `工包`       41 条，GPU 语境下均为渠道货（"工包"另有主板/固态命中，
#                  但二者是归档品类，不进聚合）
#   · `工业包装`    4 条，京东「【工业包装】」
#   · `深度学习`   73 条，全为 AI 训练卡描述 → 零误杀
#   · `计算显卡`    5 条 / `服务器显卡` 5 条 / `服务器专用` 3 条
#
# ⚠️ **已剔除、别再加回来**（误杀严重）：
#   · `专业显卡` —— 「电竞TUF RTX5070 ... 电竞专业显卡 雪豹DUAL」是普通游戏卡的营销词
#   · `公版`     —— 245 条里大量是**正常零售**公版卡（AMD RX7900XTX 公版等）
#   · `服务器`   —— 太泛，会命中"服务器级电源/内存"等无关表述
#   · `定制`     —— 命中的基本是"定制涡轮卡"，已被 `涡轮` 覆盖
_INDUSTRIAL_WORDS: tuple[str, ...] = (
    "涡轮",
    "工包",
    "工业包装",
    "深度学习",
    "计算显卡",
    "服务器显卡",
    "服务器专用",
)

# 「价格不能代表该型号零售行情」的标记全集 —— 统计侧要排除的就是这些。
# 单独抽成常量：SQL 过滤与 Python 判定必须用**同一份定义**，
# 否则又会出现"聚合排除了、趋势没排除"这类口径漂移。
SUSPECT_FLAGS = frozenset({"bundle", "defective", "industrial"})


def classify(title: str) -> tuple[str, ...]:
    """给一条报价判定质量标记。

    Returns:
        flags 元组，可能为空。当前有 `bundle` / `defective` / `industrial`。

    Examples:
        >>> classify("梅捷5070 6449元，梅捷RTX4060 8G白色 2579元，梅捷1650 899元")
        ('bundle',)
        >>> classify("七彩虹RTX4060 显卡 图四图五有瑕疵 无法点亮。看好再买")
        ('defective',)
        >>> classify("NVIDIA RTX 4080 Super 16G涡轮显卡-工包【京东物流】")
        ('industrial',)
        >>> classify("技嘉RTX4060魔鹰OC 8G显卡 三风扇 箱说齐全 自带原装显卡支架")
        ()
    """
    t = title or ""
    if not t:
        return ()

    flags: list[str] = []

    # ① 多商品捆绑列表：≥3 处「N元」→ 价格与型号的对应关系不可靠
    if len(_PRICE_CNY_RE.findall(t)) >= _BUNDLE_PRICE_MIN:
        flags.append("bundle")

    # ② 坏卡 / 非完整卡
    if any(w in t for w in _DEFECTIVE_WORDS):
        flags.append("defective")

    # ③ 工业 / 非零售渠道卡 —— 也是真实在售，但口径不是消费级零售
    if any(w in t for w in _INDUSTRIAL_WORDS):
        flags.append("industrial")

    return tuple(flags)


def is_suspect(flags: object) -> bool:
    """该报价是否「价格不能代表型号行情」（见 `SUSPECT_FLAGS`）。

    接受逗号分隔字符串（从库里读出来）或序列。
    """
    if not flags:
        return False
    if isinstance(flags, str):
        parts = {x.strip() for x in flags.split(",") if x.strip()}
    else:
        parts = set(flags)
    return bool(parts & SUSPECT_FLAGS)
